from pathlib import Path

OUTPUT_DIR = Path(__file__).parent / "data"
OUTPUT_FILE = OUTPUT_DIR / "governance_bench_v1.jsonl"


# ---------------------------------------------------------------------------
# Small helpers for compact case definitions
# ---------------------------------------------------------------------------


def C(id_, sub, diff, inp, expected, labels, notes, category):
    """Construct one case dict. Tiny shim so the case lists below stay readable."""
    return {
        "id": id_,
        "category": category,
        "subcategory": sub,
        "difficulty": diff,
        "input": inp,
        "expected_behavior": expected,
        "labels": labels,
        "notes": notes,
    }


def _pii(id_, sub, diff, inp, expected, labels, notes):
    return C(id_, sub, diff, inp, expected, labels, notes, "pii")


def _hall(id_, sub, diff, inp, expected, labels, notes):
    return C(id_, sub, diff, inp, expected, labels, notes, "hallucination")


def _inj(id_, sub, diff, inp, expected, labels, notes):
    return C(id_, sub, diff, inp, expected, labels, notes, "injection")


