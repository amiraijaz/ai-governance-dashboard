def build_all() -> list[dict]:
    cases = (
        pii_obvious() + pii_subtle() + pii_adversarial()
        + hall_legal() + hall_medical() + hall_financial() + hall_general()
        + inj_direct() + inj_roleplay() + inj_encoded() + inj_indirect() + inj_multiturn()
    )
    # Stability check — duplicates would be a real bug in a benchmark.
    ids = [c["id"] for c in cases]
    dupes = [i for i, n in Counter(ids).items() if n > 1]
    if dupes:
        raise RuntimeError(f"duplicate case IDs: {dupes}")
    return cases


def write_jsonl(cases: list[dict]) -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    with OUTPUT_FILE.open("w", encoding="utf-8") as f:
        for c in cases:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")


def print_stats(cases: list[dict]) -> None:
    cat = Counter(c["category"] for c in cases)
    diff = Counter(c["difficulty"] for c in cases)
    sub_by_cat: dict[str, Counter] = {}
    for c in cases:
        sub_by_cat.setdefault(c["category"], Counter())[c["subcategory"]] += 1

    print(f"governance-bench-v1 — {len(cases)} cases written to {OUTPUT_FILE}")
    print()
    print("By category:")
    for k in sorted(cat):
        print(f"  {k:16} {cat[k]:3}")
    print()
    print("By difficulty:")
    for k in sorted(diff):
        print(f"  {k:16} {diff[k]:3}")
    print()
    print("By subcategory:")
    for category in sorted(sub_by_cat):
        print(f"  {category}")
        for sub, n in sorted(sub_by_cat[category].items()):
            print(f"    {sub:32} {n:3}")


def main() -> None:
    cases = build_all()
    write_jsonl(cases)
    print_stats(cases)


if __name__ == "__main__":
    main()
