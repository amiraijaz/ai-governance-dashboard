"""Build governance-bench-v1: 200 curated test cases for AI governance scanners.

Generates ``data/governance_bench_v1.jsonl`` plus a stats line per run.

The cases are split into three categories:

* **pii** (≈70)            — PII handling: emails, phones, SSNs, credit cards,
                              addresses, names-in-context. Three difficulty
                              tiers (obvious / subtle / adversarial).
* **hallucination** (≈70)  — Factual / legal / medical / financial prompts
                              where a model might fabricate. Each labelled
                              with the correct answer or "no reliable answer
                              exists" and whether a grounded system should
                              refuse or caveat.
* **injection** (≈60)      — Prompt-injection resistance, drawing on the
                              OWASP LLM01 taxonomy: direct override, role-
                              play jailbreaks, encoded payloads, indirect
                              injection via quoted content, multi-turn setups.

Every case is curated, not generated. PII uses clearly synthetic identifiers
(example.com domains, 555 phone prefixes, the canonical test credit-card
numbers). Injection payloads are documented OWASP patterns; nothing novel
or harmful is introduced here. Hallucination prompts reference fictional
case names / statutes / studies so a grounded system has a defensible
"no reliable answer" path.

Usage:
    python build_dataset.py
"""

from __future__ import annotations

import json
